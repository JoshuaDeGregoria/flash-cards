def to_canvas_ak(lon, lat):
    x = AK_LEFT + (lon - AK_WEST)   / (AK_EAST  - AK_WEST)  * AK_WIDTH
    y = AK_TOP  + (AK_NORTH - lat)  / (AK_NORTH - AK_SOUTH) * AK_HEIGHT
    return x, y


