def inset_flat(point_list, proj_fn):
    """Same as points_to_flat but uses a custom projection function."""
    flat = []
    for lon, lat in point_list:
        x, y = proj_fn(lon, lat)
        flat.append(x)
        flat.append(y)
    return flat


